    <h1>What a registrar auditor looks for during an ISO audit</h1>
    <div class="article-content">

<p>During an ISO 9001 certification audit, the registrar auditor is not looking for perfection. Instead, they are verifying that the company has a functioning quality management system that meets the requirements of the standard.</p>
<p>Auditors typically begin by reviewing the company’s scope, quality policy, and objectives. They want to understand how the organization defines quality and how leadership supports the system.</p>
<p>Next, the auditor evaluates core processes. In manufacturing environments this often includes order review, purchasing controls, production planning, inspection activities, and handling of nonconforming product. The auditor will follow real jobs through the system to confirm that procedures match actual practice.</p>
<p>Evidence is critical. Auditors look for records such as inspection results, calibration certificates, training documentation, and corrective action reports. These records demonstrate that the system operates consistently.</p>
<p>Internal audits and management reviews are also closely examined. These activities show that the company actively monitors its system and addresses weaknesses before they become major issues.</p>


